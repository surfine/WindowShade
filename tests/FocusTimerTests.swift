import Foundation

@main
struct FocusTimerTests {
    static func main() {
        var t = TestSuite("T1")

        let cal = FocusTimer.CalendarSample(today: "2026-10-03", deadlineDay: "2026-10-03")
        t.section("T1-01", "空闲开始 25+5 → 截止时刻 1500 秒，聊天收起一次")
        var a = FocusTimer(bootID: fixtureBoot)
        t.expect(a.nextWake(at: sec(0), presentation: .compact) == nil, "空闲不排刷新")
        let start = a.handle(.start, at: sec(0), calendar: cal)
        t.expect(a.phase == .focus && a.deadline == sec(1500), "开始不是累计 tick")
        t.expect(start.count == 1 && a.handle(.start, at: sec(0), calendar: cal).isEmpty, "重复开始无重复窗口动作")
        t.section("T1-02", "紧凑/展开/隐藏 → 分别排分钟、秒、截止唤醒")
        t.expect(a.nextWake(at: sec(0), presentation: .compact) == sec(60), "紧凑整分钟")
        t.expect(a.nextWake(at: sec(0), presentation: .expanded) == sec(1), "展开一秒")
        t.expect(a.nextWake(at: sec(0), presentation: .hidden) == sec(1500), "隐藏只有到点")
        t.expect(a.compactText(at: sec(420)) == "18 分", "18 分原文")
        t.expect(a.compactText(at: sec(1458)) == "0:42", "最后一分钟秒数")
        t.expect(a.nextWake(at: sec(1458.25), presentation: .compact) == sec(1459), "秒显示与截止对齐")
        t.section("T1-03", "专注自然到点再休息到点 → 计数一次，不自动下一轮")
        let focusEnd = a.handle(.tick, at: sec(1500), calendar: cal)
        t.expect(a.phase == .rest && a.completedToday == 1 && a.deadline == sec(1800), "完整专注才计数")
        t.expect(focusEnd.contains(.sound(.restStarted)), "真实到点提示音")
        let restEnd = a.handle(.tick, at: sec(1800), calendar: cal)
        t.expect(a.phase == .idle && restEnd.contains(.sound(.restFinished)), "休息完空闲")
        t.expect(a.handle(.tick, at: sec(1800), calendar: cal).isEmpty, "重复 tick 无补发")
        t.section("T1-04", "手动暂停叠加锁屏 → 单独继续不解除锁屏暂停")
        var b = FocusTimer(bootID: fixtureBoot)
        _ = b.handle(.start, at: sec(0), calendar: cal)
        _ = b.handle(.pause, at: sec(10), calendar: cal)
        _ = b.handle(.locked, at: sec(20), calendar: cal)
        _ = b.handle(.resume, at: sec(30), calendar: cal)
        t.expect(b.isPaused && b.pauses == [.locked] && b.remaining(at: sec(40)) == 1490 * WS2.Duration.second, "暂停原因独立")
        t.expect(b.nextWake(at: sec(40), presentation: .expanded) == nil, "暂停不醒来")
        _ = b.handle(.unlocked, at: sec(50), calendar: cal)
        t.expect(b.deadline == sec(1540), "正确顺延剩余时间")
        t.section("T1-05", "睡眠叠加锁屏，先唤醒后解锁 → 最后一个原因解除才计时")
        _ = b.handle(.sleep, at: sec(60), calendar: cal)
        _ = b.handle(.locked, at: sec(70), calendar: cal)
        _ = b.handle(.wake, at: sec(80), calendar: cal)
        t.expect(b.pauses == [.locked], "唤醒不能解锁")
        _ = b.handle(.unlocked, at: sec(100), calendar: cal)
        t.expect(b.deadline == sec(1580), "睡眠期间无扣秒")
        t.section("T1-06", "休息睡两小时 → 已结束，不补播开始或结束音")
        var c = FocusTimer(bootID: fixtureBoot)
        _ = c.handle(.start, at: sec(0), calendar: cal); _ = c.handle(.tick, at: sec(1500), calendar: cal)
        _ = c.handle(.sleep, at: sec(1510), calendar: cal)
        let wake = c.handle(.wake, at: sec(8710), calendar: cal)
        t.expect(c.phase == .idle && !wake.contains(.sound(.restFinished)) && !wake.contains(.sound(.restStarted)), "休息不因睡眠冻结")
        t.section("T1-07", "专注到点同刻锁屏 → 结算次数，但不收全桌面、不响铃")
        var d = FocusTimer(bootID: fixtureBoot)
        _ = d.handle(.start, at: sec(0), calendar: cal)
        let locked = d.handle(.locked, at: sec(1500), calendar: cal)
        t.expect(d.completedToday == 1 && d.phase == .rest, "已完成专注仍计数")
        t.expect(!locked.contains(where: { if case .tuckAll = $0 { return true }; if case .sound = $0 { return true }; return false }), "锁屏先于可见效果")
        t.section("T1-08", "专注跳过和主动结束 → 都不增加完成数")
        var e = FocusTimer(bootID: fixtureBoot)
        _ = e.handle(.start, at: sec(0), calendar: cal); _ = e.handle(.skip, at: sec(3), calendar: cal)
        t.expect(e.phase == .rest && e.completedToday == 0, "跳过不算完成")
        _ = e.handle(.end, at: sec(4), calendar: cal)
        t.expect(e.phase == .idle, "结束清理")
        _ = e.handle(.start, at: sec(5), calendar: cal); _ = e.handle(.end, at: sec(1505), calendar: cal)
        t.expect(e.completedToday == 0, "明确结束优先于同刻自然结束")
        t.section("T1-09", "休息关掉收起的窗口 → 计时继续，恢复只发一次")
        var f = FocusTimer(bootID: fixtureBoot)
        _ = f.handle(.start, at: sec(0), calendar: cal); _ = f.handle(.tick, at: sec(1500), calendar: cal)
        let restore = f.handle(.dismissRestWindows, at: sec(1510), calendar: cal)
        t.expect(f.phase == .rest && restore.count == 1, "只撤销本轮窗口归属")
        t.expect(f.handle(.dismissRestWindows, at: sec(1511), calendar: cal).isEmpty, "重复关闭无动作")
        t.section("T1-10", "旧日期的 deadline 晚到新日期 → 不记到今天，不闪过已过去的休息")
        var g = FocusTimer(bootID: fixtureBoot)
        _ = g.handle(.start, at: sec(0), calendar: cal)
        let late = g.handle(.tick, at: sec(4000), calendar: .init(today: "2026-10-04", deadlineDay: "2026-10-03"))
        t.expect(g.completedToday == 0 && g.phase == .idle && !late.contains(where: { if case .tuckAll = $0 { return true }; return false }), "晚到不补播")
        t.section("T1-11", "50+10，关闭聊天收起 → 3000 秒专注、600 秒休息")
        var h = FocusTimer(bootID: fixtureBoot, preset: .minutes50, tuckChatEnabled: false)
        t.expect(h.handle(.start, at: sec(0), calendar: cal).isEmpty && h.deadline == sec(3000), "关闭选项不收聊天")
        _ = h.handle(.tick, at: sec(3000), calendar: cal)
        t.expect(h.deadline == sec(3600), "十分钟休息")
        t.section("T1-12", "时间倒流/无效日期/锁屏开始 → 拒绝，不启动第二轮")
        t.expect(h.handle(.tick, at: sec(1), calendar: cal) == [.fault(.timeReversed)], "拒绝倒流")
        var z = FocusTimer(bootID: fixtureBoot)
        _ = z.handle(.locked, at: sec(0), calendar: cal)
        t.expect(z.handle(.start, at: sec(1), calendar: cal).isEmpty && z.phase == .idle, "锁着不开始")
        t.expect(z.handle(.start, at: sec(2), calendar: .init(today: "", deadlineDay: "")) == [.fault(.malformedInput)], "日期不可伪空")

        func reminders(_ effects: [FocusTimer.Effect]) -> [FocusTimer.Reminder] {
            effects.compactMap { e -> FocusTimer.Reminder? in if case .remind(let x) = e { return x }; return nil }
        }
        t.section("T10-01", "专注自然结束 → 提醒“休息 5 分钟”，副句今天第 n 个，停 2.4 秒，不自动开始")
        var r = FocusTimer(bootID: fixtureBoot)
        _ = r.handle(.start, at: sec(0), calendar: cal)
        let done1 = r.handle(.tick, at: sec(1500), calendar: cal)
        let reminders1 = reminders(done1)
        t.expect(reminders1.count == 1 && reminders1[0].title == "休息 5 分钟" && reminders1[0].detail == "专注完成 · 今天第 1 个", "文案")
        t.expect(reminders1[0].hold == 2.4 && reminders1[0].symbol == "cup.and.saucer" && !reminders1[0].startsNextFocus, "停留与符号，点击不开始下一轮")
        t.expect(done1.contains(.sound(.restStarted)), "保留轻提示音")
        t.section("T10-02", "50 分钟档 → 写“休息 10 分钟”；第二个写今天第 2 个")
        var r50 = FocusTimer(bootID: fixtureBoot, preset: .minutes50)
        _ = r50.handle(.start, at: sec(0), calendar: cal); _ = r50.handle(.tick, at: sec(3000), calendar: cal)
        _ = r50.handle(.end, at: sec(3001), calendar: cal)
        _ = r50.handle(.start, at: sec(3002), calendar: cal)
        let nth = reminders(r50.handle(.tick, at: sec(6002), calendar: cal))
        t.expect(nth.first?.title == "休息 10 分钟" && nth.first?.detail == "专注完成 · 今天第 2 个", "50 分钟档与计数")
        t.section("T10-03", "休息自然结束 → “休息好了 / 再来一个？”停 5 秒；不自动开始下一轮")
        let reminders2 = reminders(r.handle(.tick, at: sec(1800), calendar: cal))
        t.expect(reminders2.count == 1 && reminders2[0].title == "休息好了" && reminders2[0].detail == "再来一个？", "文案")
        t.expect(reminders2[0].hold == 5 && reminders2[0].startsNextFocus, "停 5 秒，点了才开始")
        t.expect(r.phase == .idle && r.deadline == nil && r.handle(.tick, at: sec(1900), calendar: cal).isEmpty, "不自动开始下一轮")
        t.section("T10-04", "跳过、锁屏、晚到 → 不弹提醒")
        var q = FocusTimer(bootID: fixtureBoot)
        _ = q.handle(.start, at: sec(0), calendar: cal)
        let skipped = reminders(q.handle(.skip, at: sec(5), calendar: cal)) + reminders(q.handle(.skip, at: sec(6), calendar: cal))
        t.expect(skipped.isEmpty, "跳过不提醒")
        var lq = FocusTimer(bootID: fixtureBoot)
        _ = lq.handle(.start, at: sec(0), calendar: cal)
        let lockedEnd = reminders(lq.handle(.locked, at: sec(1500), calendar: cal)) + reminders(lq.handle(.tick, at: sec(9000), calendar: cal))
        t.expect(lockedEnd.isEmpty, "锁屏与晚到不提醒")
        t.section("T10-05", "呼吸光环：只在休息、且没开减少动态效果时呼吸；帧率范围照规定")
        t.expect(FocusBreath.breathes(phase: .rest, reduceMotion: false), "休息呼吸")
        t.expect(!FocusBreath.breathes(phase: .rest, reduceMotion: true), "减少动态效果不呼吸")
        t.expect(!FocusBreath.breathes(phase: .focus, reduceMotion: false) && !FocusBreath.breathes(phase: .idle, reduceMotion: false), "专注与空闲不呼吸")
        t.expect(FocusBreath.period == 5.5 && FocusBreath.scaleLow == 0.78 && FocusBreath.opacityLow == 0.55, "周期与幅度照稿")
        t.expect(FocusBreath.countdownFrameRate == (1, 8, 4) && FocusBreath.breathFrameRate == (10, 30, 20), "帧率范围")

        t.section("POMO", "走完留 4 秒、跳过 / 结束立即收、走完同刻锁屏立即收")
        var po = FocusTimer(bootID: fixtureBoot)
        _ = po.handle(.start, at: sec(0), calendar: cal)
        _ = po.handle(.tick, at: sec(1500), calendar: cal)
        t.expect(po.phase == .rest && po.lastEnd == nil && !po.lingersAfterEnd, "休息中还没收")
        _ = po.handle(.tick, at: sec(1800), calendar: cal)
        t.expect(po.phase == .idle && po.lastEnd == .completed && po.lingersAfterEnd, "自己走完：两耳留 4 秒")
        _ = po.handle(.start, at: sec(1900), calendar: cal)
        t.expect(po.lastEnd == nil && !po.lingersAfterEnd, "开始新一轮清掉上一轮的收法")
        var ps = FocusTimer(bootID: fixtureBoot)
        _ = ps.handle(.start, at: sec(0), calendar: cal)
        _ = ps.handle(.skip, at: sec(5), calendar: cal)
        _ = ps.handle(.skip, at: sec(6), calendar: cal)
        t.expect(ps.phase == .idle && ps.lastEnd == .skipped && !ps.lingersAfterEnd, "跳过立即收")
        var pe = FocusTimer(bootID: fixtureBoot)
        _ = pe.handle(.start, at: sec(0), calendar: cal)
        _ = pe.handle(.end, at: sec(5), calendar: cal)
        t.expect(pe.lastEnd == .ended && !pe.lingersAfterEnd, "结束立即收")
        var pl = FocusTimer(bootID: fixtureBoot)
        _ = pl.handle(.start, at: sec(0), calendar: cal)
        _ = pl.handle(.tick, at: sec(1500), calendar: cal)
        _ = pl.handle(.locked, at: sec(1800), calendar: cal)
        t.expect(pl.phase == .idle && pl.lastEnd == .completed && !pl.lingersAfterEnd, "走完同刻锁屏：立即收")
        var pz = FocusTimer(bootID: fixtureBoot)
        _ = pz.handle(.start, at: sec(0), calendar: cal)
        _ = pz.handle(.tick, at: sec(9000), calendar: cal)
        t.expect(pz.phase == .idle && pz.lastEnd == .lapsed && !pz.lingersAfterEnd, "睡过头才发现：不留")

        var pw = FocusTimer(bootID: fixtureBoot)
        _ = pw.handle(.start, at: sec(0), calendar: cal)
        _ = pw.handle(.tick, at: sec(1500), calendar: cal)
        _ = pw.handle(.tick, at: sec(1850), calendar: cal)
        t.expect(pw.phase == .idle && pw.lastEnd == .lapsed && !pw.lingersAfterEnd, "休息晚到很久才结算：不留")

        t.finish()
    }
}
